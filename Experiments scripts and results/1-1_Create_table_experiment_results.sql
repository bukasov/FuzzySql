CREATE TABLE experiment_results (
    test_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    data_volume NUMBER,           -- 10000, 100000, 1000000
    architecture VARCHAR2(20),    -- 'EAV' або 'FLAT_TABLE'
    query_type VARCHAR2(50),      -- 'FUZZY_COUNT', 'FUZZY_AVG', 'COMBINED_SEARCH', 'PARETO'
    elapsed_ms NUMBER,            -- Час виконання (мс)
    notes VARCHAR2(200)           -- Наприклад, 'Cold Cache' або 'Warm Cache'
);

-- Таблиця для збереження логів
CREATE TABLE test_execution_log (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_time TIMESTAMP DEFAULT SYSTIMESTAMP,
    message VARCHAR2(1000)
);

-- Процедура, яка пише в лог і робить COMMIT незалежно від основного скрипта
CREATE OR REPLACE PROCEDURE log_msg(p_msg VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO test_execution_log (message) VALUES (p_msg);
    COMMIT;
END;
