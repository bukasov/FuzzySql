CREATE TABLE experiment_results (
    test_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    data_volume NUMBER,           -- 10000, 100000, 1000000
    architecture VARCHAR2(20),    -- 'EAV' або 'FLAT_TABLE'
    query_type VARCHAR2(50),      -- 'FUZZY_COUNT', 'FUZZY_AVG', 'COMBINED_SEARCH', 'PARETO'
    elapsed_ms NUMBER,            -- Час виконання (мс)
    notes VARCHAR2(200)           -- Наприклад, 'Cold Cache' або 'Warm Cache'
);


